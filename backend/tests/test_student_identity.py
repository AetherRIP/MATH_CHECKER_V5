"""Canonical student display name — the eight scenarios in the brief §19.

The bug these lock down is a data-flow bug, not a cosmetic one: the Google
Classroom name reached the correction job but was lost before the result row,
so the correction result page had no name to show and no stable key to look
one up by. The name is therefore resolved through
:mod:`app.student_identity` from stable Classroom ids, and these tests assert
the whole flow — page payload, PDF text, history, and identity stability when
a nickname changes.
"""

from __future__ import annotations

import pytest

from app import db
from app import student_identity as si


