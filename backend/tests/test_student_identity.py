NICKNAME = "Mo"
STUDENT_ID = "111111111111111111111"
OTHER_ID = "222222222222222222222"
SUBMISSION_ID = "submission-abc"
COURSEWORK_ID = "cw-1"
JOB_ID = "job-1"
RESULT_ID = "res-1"


