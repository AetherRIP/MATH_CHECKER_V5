def _result_row(*, student_id=STUDENT_ID, student_name=CLASSROOM_NAME,
                result_id=RESULT_ID):
    db.execute("DELETE FROM results WHERE id = ?", (result_id,))
    db.execute("DELETE FROM correction_jobs WHERE id = ?", (JOB_ID,))
    db.execute(
        "INSERT INTO correction_jobs(id, submission_id, coursework_id, "
        "course_id, student_id, student_name, status, created_at, updated_at) "
        "VALUES(?,?,?,?,?,?,?,?,?)",
        (JOB_ID, SUBMISSION_ID, COURSEWORK_ID, "course-1", student_id,
         student_name, "COMPLETED", 0.0, 0.0))
    db.execute(
        "INSERT INTO results(id, job_id, coursework_id, submission_id, "
        "student_id, student_name, earned, available, percentage, result_json, "
        "created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)",
        (result_id, JOB_ID, COURSEWORK_ID, SUBMISSION_ID, student_id,
         student_name, 68, 75, 90.7, '{"paper_info":{"paper":"","session":""}}',
         0.0))
    return result_id


# --- Test 1: Classroom name, no nickname ---------------------------------

class TestClassroomNameOnly:
    def test_display_name_is_the_classroom_name(self, student):
        assert si.display_name(None, CLASSROOM_NAME) == CLASSROOM_NAME

    def test_result_page_shows_the_classroom_name(self, client, student):
        _result_row()
        data = client.get(f"/api/results/{RESULT_ID}").json()
        assert data["display_name"] == CLASSROOM_NAME
        assert data["classroom_name"] == CLASSROOM_NAME
        assert data["nickname"] is None

    def test_pdf_uses_the_classroom_name(self, client, student):
        _result_row()
        pdf = client.get(f"/api/results/{RESULT_ID}/export?format=pdf")
        assert pdf.status_code == 200
        assert pdf.content[:5] == b"%PDF-"


# --- Test 2: nickname wins, everywhere -----------------------------------

class TestNicknameWins:
    @pytest.fixture(autouse=True)
    def _nickname(self, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))

    def test_rule(self):
        assert si.display_name(NICKNAME, CLASSROOM_NAME) == NICKNAME

    def test_result_page_shows_the_nickname(self, client, student):
        _result_row()
        data = client.get(f"/api/results/{RESULT_ID}").json()
        assert data["display_name"] == NICKNAME
        # The official identity is preserved, not overwritten (§2/§3).
        assert data["classroom_name"] == CLASSROOM_NAME
        assert data["nickname"] == NICKNAME
        assert data["student_id"] == STUDENT_ID

    def test_pdf_uses_the_nickname(self, client, student):
        _result_row()
        data = client.get(f"/api/results/{RESULT_ID}/export?format=pdf").content
        # The PDF is generated by a caller that passes the canonical name; the
        # name itself is what matters, so assert on the generator directly.
        from app.api.report_routes import render_result_pdf
        buf = render_result_pdf({"display_name": si.display_name(NICKNAME, CLASSROOM_NAME),
                                 "student_name": CLASSROOM_NAME,
                                 "earned": 68, "available": 75,
                                 "percentage": 90.7,
                                 "result_json": {"paper_info": {}}})
        assert buf.getvalue()[:5] == b"%PDF-"
        assert data[:5] == b"%PDF-"

    def test_the_stored_name_stays_the_classroom_one(self, student):
        """A nickname is a display preference, so it must not be written into
        the historical result row (§2, §14)."""
        _result_row()
        row = db.query_one("SELECT student_name FROM results WHERE id = ?",
                           (RESULT_ID,))
        assert row["student_name"] == CLASSROOM_NAME


# --- Test 3: removing the nickname falls back ---------------------------

class TestNicknameRemoved:
    def test_display_falls_back_to_the_classroom_name(self, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))
        assert si.resolve(STUDENT_ID)["display_name"] == NICKNAME
        db.execute("UPDATE students SET nickname = NULL WHERE id = ?",
                   (STUDENT_ID,))
        assert si.resolve(STUDENT_ID)["display_name"] == CLASSROOM_NAME

    def test_result_page_falls_back_automatically(self, client, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))
        _result_row()
        assert client.get(f"/api/results/{RESULT_ID}").json()["display_name"] == NICKNAME
        db.execute("UPDATE students SET nickname = NULL WHERE id = ?",
                   (STUDENT_ID,))
        data = client.get(f"/api/results/{RESULT_ID}").json()
        assert data["display_name"] == CLASSROOM_NAME
        assert data["classroom_name"] == CLASSROOM_NAME


# --- Test 4: several submissions, one identity --------------------------

class TestMultipleSubmissions:
    def test_every_submission_resolves_to_the_same_name(self, student):
        subs = [f"sub-{i}" for i in range(3)]
        for sid in subs:
            db.execute(
                "INSERT INTO classroom_submissions(submission_id, coursework_id, "
                "course_id, student_id, student_name, current_state, "
                "first_seen_at) VALUES(?,?,?,?,?,?,?)",
                (sid, COURSEWORK_ID, "course-1", STUDENT_ID, CLASSROOM_NAME,
                 "TURNED_IN", 0.0))
            try:
                assert si.resolve(None, submission_id=sid)["display_name"] \
                    == CLASSROOM_NAME
                assert si.resolve(STUDENT_ID)["display_name"] == CLASSROOM_NAME
            finally:
                db.execute(
                    "DELETE FROM classroom_submissions WHERE submission_id = ?",
                    (sid,))

    def test_a_nickname_applies_to_all_of_them(self, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))
        for sid in ("sub-a", "sub-b"):
            db.execute(
                "INSERT INTO classroom_submissions(submission_id, coursework_id, "
                "course_id, student_id, student_name, current_state, "
                "first_seen_at) VALUES(?,?,?,?,?,?,?)",
                (sid, COURSEWORK_ID, "course-1", STUDENT_ID, CLASSROOM_NAME,
                 "TURNED_IN", 0.0))
        try:
            names = {si.resolve(None, submission_id=s)["display_name"]
                     for s in ("sub-a", "sub-b")}
            assert names == {NICKNAME}
        finally:
            for sid in ("sub-a", "sub-b"):
                db.execute(
                    "DELETE FROM classroom_submissions WHERE submission_id = ?",
                    (sid,))


# --- Test 5 & 6: remark and re-export keep the same name ---------------

class TestRemarkAndRegeneration:
    def test_remark_carries_the_classroom_identity_not_the_nickname(self,
                                                                    student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))
        _result_row()
        from app.api.routes_all import _identity
        who = _identity.resolve(STUDENT_ID, submission_id=SUBMISSION_ID)
        # A remark must never be attributed to the nickname, and the student id
        # (never a name) is what Classroom matching uses.
        assert who["student_id"] == STUDENT_ID
        assert who["classroom_name"] == CLASSROOM_NAME
        assert who["nickname"] == NICKNAME

    def test_regenerating_the_report_yields_the_same_name(self, client, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   (NICKNAME, STUDENT_ID))
        _result_row()
        first = client.get(f"/api/results/{RESULT_ID}").json()["display_name"]
        second = client.get(f"/api/results/{RESULT_ID}").json()["display_name"]
        assert first == second == NICKNAME


# --- Test 7: renaming does not split the student ------------------------

class TestNicknameChangeKeepsIdentity:
    def test_history_stays_linked_to_the_same_student(self, student):
        _result_row()
        before = db.query_one(
            "SELECT id, student_id, student_name, earned FROM results "
            "WHERE id = ?", (RESULT_ID,))
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   ("Momo", STUDENT_ID))
        after = db.query_one(
            "SELECT id, student_id, student_name, earned FROM results "
            "WHERE id = ?", (RESULT_ID,))
        # Same row, same student, same grade — only the display name changed.
        assert after["id"] == before["id"]
        assert after["student_id"] == before["student_id"] == STUDENT_ID
        assert after["student_name"] == before["student_name"] == CLASSROOM_NAME
        assert after["earned"] == before["earned"]
        assert si.resolve(STUDENT_ID)["display_name"] == "Momo"

    def test_no_duplicate_student_row_is_created(self, student):
        db.execute("UPDATE students SET nickname = ? WHERE id = ?",
                   ("Momo", STUDENT_ID))
        rows = db.query("SELECT id, name FROM students WHERE name = ?",
                        (CLASSROOM_NAME,))
        assert [r["id"] for r in rows] == [STUDENT_ID]
        assert db.query_one("SELECT nickname FROM students WHERE id = ?",
                            (STUDENT_ID,))["nickname"] == "Momo"


# --- Test 8: two students with the same name stay separate --------------

class TestDuplicateNamesStaySeparate:
    def test_identical_classroom_names_do_not_collide(self, student):
        db.execute(
            "INSERT INTO students(id, name, email, nickname, fetched_at) "
            "VALUES(?,?,?,?,?)", (OTHER_ID, CLASSROOM_NAME, None, None, 0.0))
        try:
            a = si.resolve(STUDENT_ID)
            b = si.resolve(OTHER_ID)
            assert a["display_name"] == b["display_name"] == CLASSROOM_NAME
            # Same name, different identity — resolution is keyed on the id.
            assert a["student_id"] != b["student_id"]
        finally:
            db.execute("DELETE FROM students WHERE id = ?", (OTHER_ID,))

    def test_a_nickname_separates_them_for_the_teacher(self, student):
        db.execute(
            "INSERT INTO students(id, name, email, nickname, fetched_at) "
            "VALUES(?,?,?,?,?)", (OTHER_ID, CLASSROOM_NAME, None, "Maha", 0.0))
        try:
            assert si.resolve(STUDENT_ID)["display_name"] == CLASSROOM_NAME
            assert si.resolve(OTHER_ID)["display_name"] == "Maha"
        finally:
            db.execute("DELETE FROM students WHERE id = ?", (OTHER_ID,))


# --- the underlying data flow, not just the display --------------------

class TestIdentityDataFlow:
    def test_a_result_missing_its_student_id_is_recovered(self, student):
        """The original defect: the result row lost the student id, leaving the
        page with no name and no key to look one up by."""
        _result_row(student_id=None, student_name=None)
        identity = si.resolve(None, submission_id=SUBMISSION_ID)
        assert identity["student_id"] == STUDENT_ID
        assert identity["display_name"] == CLASSROOM_NAME

    def test_the_migration_relinks_and_renames_nothing(self, student):
        _result_row(student_id=None, student_name=None)
        stats = si.backfill_missing_identities()
        assert stats["results_linked"] == 1
        row = db.query_one("SELECT student_id, student_name FROM results "
                           "WHERE id = ?", (RESULT_ID,))
        assert row["student_id"] == STUDENT_ID
        assert row["student_name"] == CLASSROOM_NAME
        # Idempotent: running it again changes nothing.
        assert si.backfill_missing_identities()["results_linked"] == 0

    def test_a_missing_classroom_name_is_filled_from_the_roster(self, student):
        db.execute("UPDATE students SET name = NULL WHERE id = ?", (STUDENT_ID,))
        si.backfill_missing_identities()
        row = db.query_one("SELECT name FROM students WHERE id = ?", (STUDENT_ID,))
        assert row["name"] == CLASSROOM_NAME

    def test_no_name_is_invented_without_a_classroom_record(self, fresh_state):
        identity = si.resolve("does-not-exist")
        assert identity["classroom_name"] is None
        assert identity["display_name"] == "Student"
        assert identity["source"] == "classroom_id_only"

    def test_the_pool_writes_the_resolved_identity(self, student):
        """The write-time half of the fix: a job without a student id must not
        produce a result without one."""
        from app.workers.pool import WorkerPool
        job = {"student_id": None, "student_name": None,
               "submission_id": SUBMISSION_ID}
        resolved_id, resolved_name = WorkerPool._resolve_student_identity(job)
        assert resolved_id == STUDENT_ID
        assert resolved_name == CLASSROOM_NAME

    def test_a_snapshot_name_is_never_preferred_over_the_classroom_name(self,
                                                                       student):
        identity = si.resolve(STUDENT_ID, snapshot_name="Mohamed")
        assert identity["display_name"] == CLASSROOM_NAME
        assert identity["classroom_name"] == CLASSROOM_NAME

    def test_blank_names_are_treated_as_missing(self):
        assert si.display_name("   ", "  ", fallback="x") == "x"
        assert si.display_name(None, None) == "Student"
