"""Attach the generated correction report to the STUDENT'S Classroom submission.

Why this module exists
----------------------
The app produced a correction PDF but only ever served it to the teacher
(/api/results/{id}/export). Nothing was ever pushed back to Google Classroom,
so a student could not see their own report. This module closes that gap:

    render PDF -> upload to Drive -> share with that one student
                -> modifyAttachments on THAT StudentSubmission
                -> re-read the StudentSubmission and VERIFY

Design rules that the rest of the app depends on
-------------------------------------------------
* **Correct student, always.** The attachment target is the Classroom
  ``submission_id`` recorded on the result row - never a display name. The
  results table stores courseWorkId + submissionId + userId, so the mapping
  Classroom student <-> StudentSubmission <-> downloaded work <-> result is
  by stable id end to end.
* **No duplicate reports.** The Drive file id is remembered per result.
  Re-attaching UPDATES that same Drive file instead of uploading a new one,
  and the previous attachment is removed before a new one is added. That is
  why you never get "Report.pdf", "Report (1).pdf", "Report (2).pdf".
* **Verified, not assumed.** ``VERIFIED`` is only recorded after re-reading
  the StudentSubmission and finding the Drive file id in its attachments.
* **Retryable without re-marking.** All state lives in ``report_attachments``,
  so a failed attachment is retried with one call; the AI marking, the PDF
  bytes and the draft grade are never redone.
* **Honest about Google's limits.** Google only lets this OAuth client
  modify submissions for coursework created by the same Developer Console
  project. When it refuses, we record BLOCKED_NOT_MODIFIABLE and say so
  instead of pretending the report was attached.
"""

