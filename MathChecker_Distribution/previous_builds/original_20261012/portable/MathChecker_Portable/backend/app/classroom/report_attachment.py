# ------------------------------------------------------------ verification

def _attachment_ids(submission: dict) -> set[str]:
    ids: set[str] = set()
    for att in (submission.get("assignmentSubmission") or {}).get(
            "attachments", []) or []:
        drive = att.get("driveFile") or {}
        if drive.get("id"):
            ids.add(drive["id"])
    return ids


def verify_attached(token: str, course_id: str, coursework_id: str,
                    submission_id: str, drive_file_id: str) -> dict:
    """Re-read the StudentSubmission and confirm our file is really on it.

    A 200 from modifyAttachments is NOT accepted as proof - Classroom returns
    the submission body even when it silently ignored part of the request.
    """
    submission = gc.get_student_submission(token, course_id, coursework_id,
                                           submission_id)
    ids = _attachment_ids(submission)
    present = drive_file_id in ids
    return {
        "verified": present,
        "drive_file_id": drive_file_id,
        "attachment_ids": sorted(ids),
        "attachment_count": len(ids),
        "can_modify": gc.submission_can_be_modified(submission),
    }


def verify_drive_accessible(token: str, drive_file_id: str) -> dict:
    """Confirm a Classroom-attached Drive file is still there and not trashed.

    The attachment is only a REFERENCE to the Drive object, so an unreachable
    or trashed file means the student cannot open it - the exact "document
    couldn't be opened" symptom. This is the post-attach check that guarantees
    we do not report a dead attachment as a success.
    """
    if not drive_file_id:
        return {"ok": False, "reason": "no_file_id", "file_id": None}
    try:
        meta = gc.get_drive_file(token, drive_file_id)
    except Exception as exc:  # noqa: BLE001 - reported, never raised
        return {"ok": False, "reason": f"drive_read_failed: {exc}",
                "file_id": drive_file_id}
    if meta is None:
        return {"ok": False, "reason": "file_missing", "file_id": drive_file_id}
    if meta.get("trashed"):
        return {"ok": False, "reason": "file_trashed", "file_id": drive_file_id}
    return {
        "ok": True, "file_id": drive_file_id,
        "name": meta.get("name"), "mimeType": meta.get("mimeType"),
        "size": meta.get("size"), "trashed": False,
    }


def _validate_pdf(content: bytes) -> dict:
    """Prove the generated bytes are a real, openable PDF BEFORE uploading.

    Lazy import so this module never hard-depends on the automation package at
    import time (the runner imports THIS module). Uses the single existing
    validator so there is exactly one definition of "a valid report PDF".
    """
    from ..automation.pdf_validation import validate_report_pdf
    return validate_report_pdf(content)


def _verify_drive_upload(token: str, drive_file_id: str, content: bytes) -> dict:
    """Prove the Drive file exists, is a PDF, and holds exactly our bytes.

    A 200 from the upload is not proof: the file might be missing, trashed,
    the wrong mime type, zero bytes, or somebody else's. This re-reads Drive
    and (when the bytes are supplied) downloads it and compares the content,
    which is what lets ``REPORT_UPLOADED`` mean something.
    """
    from ..automation.pdf_validation import verify_drive_report
    return verify_drive_report(token, drive_file_id, expected_bytes=content)


def _mark_canonical(course_id: str, coursework_id: str, submission_id: str,
                    result_id: str, *, drive_file_id: str | None = None) -> None:
    """Record that ``result_id`` is the canonical correction report for one

    submission. A future re-correction for the SAME submission replaces the
    canonical Drive file in place instead of adding a second Math Correct file
    (Classroom has no removeAttachments).

    Safe to call repeatedly — it is idempotent and only ever writes our own
    Math Correct metadata.
    """
    execute(
        """INSERT INTO canonical_reports(
            course_id, coursework_id, submission_id, canonical_result_id,
            drive_file_id, updated_at)
        VALUES(?,?,?,?,?,?)
        ON CONFLICT(course_id, coursework_id, submission_id) DO UPDATE SET
            canonical_result_id = excluded.canonical_result_id,
            drive_file_id = excluded.drive_file_id,
            updated_at = excluded.updated_at
        """,
        (course_id, coursework_id, submission_id, result_id,
         drive_file_id, time.time()))


def _canonical_for_submission(course_id: str, coursework_id: str,
                              submission_id: str,
                              *, token: str | None = None) -> tuple[str | None, list[dict]]:
    """Return (canonical_result_id, superseded_files) for one submission.

    ``superseded_files`` is the list of Math Correct Drive files currently on
    the submission that belong to a result OTHER than the canonical one (if
    any). Used by :func:`attach_report` before it decides whether to add a new
    file or replace the existing canonical file in place.

    When ``token`` is supplied and a canonical Drive file id is recorded, the
    superseded files are discovered by re-reading the submission's attachments
    and filtering for our own Math Correct files whose ``mathcorrectResultId``
    is NOT the canonical result id.
    """
    row = query_one(
        "SELECT canonical_result_id, drive_file_id FROM canonical_reports "
        "WHERE course_id = ? AND coursework_id = ? AND submission_id = ?",
        (course_id, coursework_id, submission_id))
    canonical_result_id = row["canonical_result_id"] if row else None
    superseded: list[dict] = []
    if token and canonical_result_id and row and row["drive_file_id"]:
        try:
            current = gc.get_student_submission(
                token, course_id, coursework_id, submission_id)
        except Exception:  # noqa: BLE001
            current = None
        if current is not None:
            existing_ids = _attachment_ids(current)
            superseded = _our_report_files_on_submission(
                token, existing_ids, exclude_result_id=canonical_result_id)
    return canonical_result_id, superseded


def _reconcile_superseded_report(token: str, course_id: str, coursework_id: str,
                                  submission_id: str, *, result_id: str,
                                  canonical_result_id: str, account_email: str | None,
                                  detail: str, render_fn) -> dict:
    """Bring the submission's current Math Correct attachment up to date.

    The submission currently points at the PRIOR canonical file (belonging to
    ``canonical_result_id``). We replace that file's bytes with the NEW report
    for ``result_id`` and then update :func:`_mark_canonical` so this result
    becomes the new canonical.

    Returns ``{drive_file_id, report_filename, previous_drive_file_id}`` for
    the file now on the submission. If the prior file cannot be reused (not
    owned by us any more), a fresh file is created and returned.
    """
    from . import report_cleanup as _cleanup

    row = query_one(
        "SELECT canonical_result_id, drive_file_id FROM canonical_reports "
        "WHERE course_id = ? AND coursework_id = ? AND submission_id = ?",
        (course_id, coursework_id, submission_id))
    if row is None:
        raise RuntimeError(
            "canonical_reports has no row for this submission (should have "
            "been created by _mark_canonical before _reconcile_superseded_report)")

    prior_result_id = row["canonical_result_id"]
    prior_file_id = row["drive_file_id"]
    # canonical_reports currently stores only canonical_result_id + drive_file_id;
    # previous_filename/previous_drive_file_id are stored on report_attachments.
    previous_filename = None
    previous_drive_file_id = None

    # Confirm the prior file is still on the submission and still ours."]
    prior_file_id = row["drive_file_id"]
    if not row or not row["drive_file_id"]:
        raise RuntimeError(
            "canonical_reports said a canonical report exists for this "
            "submission but no Drive file id was recorded")

    prior_file_id = row["drive_file_id"]
    prior_result_id = row["canonical_result_id"]
    # canonical_reports currently stores only canonical_result_id + drive_file_id;
    # previous_filename/previous_drive_file_id are stored on report_attachments.
    previous_filename = None
    previous_drive_file_id = None

    # Confirm the prior file is still on the submission and still ours.
    current = gc.get_student_submission(token, course_id, coursework_id,
                                        submission_id)
    existing_ids = _attachment_ids(current)
    if prior_file_id not in existing_ids:
        # The prior file is no longer on the submission (unlikely, but
        # defensive): fall back to a fresh upload path below.
        prior_file_id = None

    # Should the prior uploaded file be re-attached (re-conducted report
    # replacing the first report for the SAME submission), or does this need a
    # fresh upload (revised/report-corrected report for a DIFFERENT submission)?
    # This is reconciled inside _reconcile_superseded_report().
    if superseded_report is not None:
        return _reconcile_superseded_report(
            token, course_id, coursework_id, submission_id,
            result_id, superseded_report["canonical_result_id"],
            superseded_report["drive_file_id"],
            superseded_report["superseded_results"], account_email,
            detail, render_fn)

    content = render_fn()
    report_hash = _report_fingerprint(
        {"id": result_id, "coursework_id": coursework_id,
         "submission_id": submission_id, "student_id": None,
         "student_name": None}, detail=detail)
    # Validate BEFORE touching Drive (same guard as attach_report).
    validation = _validate_pdf(content)
    if not validation.get("ok"):
        raise RuntimeError(
            f"the replacement report is not a valid PDF "
            f"({validation.get('reason')})")

    # Reuse the prior file if we still own it (in-place update = one file).
    if prior_file_id:
        ownership = gc.verify_drive_ownership(
            token, prior_file_id, account_email=account_email)
        if ownership["ok"]:
            gc.replace_drive_file_content(token, prior_file_id, content)
            drive_check = _verify_drive_upload(token, prior_file_id, content)
            if not drive_check.get("ok"):
                raise RuntimeError(
                    f"the replaced Drive file did not verify "
                    f"({drive_check.get('reason')})")
            new_file_id = prior_file_id
            previous_drive_file_id = (
                row["previous_drive_file_id"] or prior_file_id)
            log_event("classroom.report", "canonical report replaced in place",
                      result_id=result_id, drive_file_id=new_file_id,
                      prior_canonical_result_id=prior_result_id)
        else:
            # We no longer own the prior file; create a fresh one (acceptable).
            prior_file_id = None

    if prior_file_id is None:
        temp_token = _cleanup.new_temp_token()
        uploaded = gc.upload_report_to_drive(
            token,
            previous_filename or build_report_filename(
                None, None),
            content,
            app_properties=_cleanup.stamp_properties(result_id, temp_token))
        new_file_id = uploaded["id"]
        previous_drive_file_id = (
            row["previous_drive_file_id"] or prior_file_id)
        owners = gc.drive_file_owners(uploaded) or []
        _cleanup.record_upload(
            result_id,
            drive_file_id=new_file_id,
            owner_email=owners[0] if owners else account_email,
            temp_token=temp_token,
            previous_drive_file_id=previous_drive_file_id,
            content_bytes=content)
        # Attach the fresh file to the submission (our prior file was gone
        # or not owned, so we must ADD it).
        try:
            gc.modify_submission_attachments(
                token, course_id, coursework_id, submission_id,
                add_drive_file_ids=[new_file_id])
        except gc.ClassroomApiError as exc:
            raise RuntimeError(
                f"Classroom refused to attach the reconciled report "
                f"({exc.status}): {exc.detail[:200]}") from exc

    return {
        "drive_file_id": new_file_id,
        "report_filename": previous_filename,
        "previous_drive_file_id": previous_drive_file_id,
    }


def _recover_attached_report(token: str, result_id: str,
                             existing_ids: set[str]) -> str | None:
    """Adopt our own report from a submission's attachments.

    A retained report keeps its Drive file id, so a NULL id means our row lost
    it (the legacy clean-after-attach rows read ``VERIFIED/CLEANED`` with no
    id). Before assuming the report is gone, look for it ON the submission:
    matched ONLY by this app's own ``appProperties`` marker for THIS result, so
    a student's own file can never be mistaken for the correction report.
    """
    for file_id in sorted(existing_ids):
        try:
            meta = gc.get_drive_file(token, file_id)
        except Exception as exc:  # noqa: BLE001 - a read failure is not fatal
            log.warning("could not read attachment %s: %s", file_id, exc)
            continue
        props = (meta or {}).get("appProperties") or {}
        if str(props.get(gc.APP_PROP_TEMP)).lower() != "true":
            continue
        if str(props.get(gc.APP_PROP_RESULT) or "") != str(result_id):
            continue
        return file_id
    return None


def _our_report_files_on_submission(token: str, existing_ids: set[str],
                                     *, exclude_result_id: str | None = None,
                                     require_ownership: bool = False,
                                     account_email: str | None = None) -> list[dict]:
    """Return the Math Correct report Drive files currently on a submission.

    Matched ONLY by this app's own ``appProperties`` markers, so a student's
    own files and mark schemes are never returned. ``exclude_result_id`` omits
    the canonical file for the result we are currently attaching (that is the
    one we want to keep / update in place).

    Each entry carries the file id, the result id it belongs to, and whether we
    still own it - used to decide whether it can be replaced in place.
    """
    out: list[dict] = []
    for file_id in sorted(existing_ids):
        try:
            meta = gc.get_drive_file(token, file_id)
        except Exception as exc:  # noqa: BLE001 - a read failure is not fatal
            log.warning("could not read attachment %s: %s", file_id, exc)
            continue
        props = (meta or {}).get("appProperties") or {}
        if str(props.get(gc.APP_PROP_TEMP)).lower() != "true":
            continue
        own_result_id = str(props.get(gc.APP_PROP_RESULT) or "")
        if own_result_id and exclude_result_id and own_result_id == exclude_result_id:
            continue
        owners = gc.drive_file_owners(meta)
        out.append({
            "drive_file_id": file_id,
            "result_id": own_result_id,
            "owned": bool(account_email and account_email in owners),
            "owners": owners,
        })
    return out


# ------------------------------------------------------------- orchestration

class AttachmentOutcome:
    """Outcome of one attach attempt (safe to render in the UI)."""

    def __init__(self, status: str, *, message: str = "", **extra: Any):
        self.status = status
        self.message = message or status
        self.extra = extra

    def to_dict(self) -> dict:
        return {"status": self.status, "message": self.message, **self.extra}


def attach_report(token: str, result: dict, *, course_id: str,
                  assignment_title: str | None = None,
                  detail: str = "standard",
                  share_with_student: bool = True,
                  account_email: str | None = None) -> AttachmentOutcome:
    """Generate -> upload -> VERIFY OWNERSHIP -> attach -> VERIFY -> CLEAN UP.

    ``result`` is the row from ``get_result()``: it carries courseWorkId,
    submissionId and studentId, which is exactly the stable-id mapping the
    attachment needs. A result without a submissionId cannot be attached to a
    student submission at all and is reported as such (never guessed from a
    display name).

    ``account_email`` is the Google identity performing the attachment. It is
    used to prove the app OWNS the Drive file before attaching (§3): Classroom
    refuses with ``@OwnerAccessRequired`` for anyone who is not an owner, and
    that refusal is permanent for that file, so it must be detected up front
    rather than retried.

    A retry re-uses the PDF bytes and the Drive file from the previous attempt,
    so the student is never re-marked, the report is never regenerated and no
    second Drive file is created (§7, §14, §15). Both are safe to re-use only
    while :func:`_report_fingerprint` still matches, so a genuine re-mark
    always produces a fresh report.

    Exactly ONE Math Correct report is kept on the submission (§1/§2/§6): if a
    previous Math Correct report is already attached for a DIFFERENT result, the
    canonical/current report replaces it in place on Drive (the Classroom API
    has no removeAttachments, so the superseded file cannot be removed — it is
    left unreachable to the student because the submission's attachment now
    points at the current file). If the SAME result is being attached again,
    the existing file is reused / updated in place and no new file is created.
    A file Classroom references is never deleted here.
    """
    result_id = result["id"]
    coursework_id = result.get("coursework_id")
    submission_id = result.get("submission_id")
    student_id = result.get("student_id")

    state = _row_for(result_id) or {}
    # The name the Drive file was ACTUALLY created with on the first run. A
    # re-run re-uses that same file (PATCH, not re-upload), so the recorded
    # name must not drift to a newly-computed one - otherwise the teacher UI
    # would report a filename that does not exist in Drive.
    previous_filename = state.get("report_filename")
    state.update({
        "result_id": result_id, "course_id": course_id,
        "coursework_id": coursework_id, "submission_id": submission_id,
        "student_id": student_id,
        "attempts": int(state.get("attempts") or 0) + 1,
    })

    if not coursework_id or not submission_id:
        state["status"] = STATUS_SKIPPED
        state["error"] = ("This correction has no Google Classroom submission, "
                          "so there is no student submission to attach to.")
        _save(state)
        return AttachmentOutcome(
            STATUS_SKIPPED, message=state["error"],
            result_id=result_id)

    filename = build_report_filename(
        result.get("display_name") or result.get("student_name"),
        assignment_title)

    # ---- canonical-report reconciliation (§1/§2/§6) ----------------
    # Before generating anything, reconcile the submission so it carries exactly
    # one Math Correct report: the canonical one for THIS result. A superseded
    # Math Correct report from a prior correction version is replaced in place
    # on Drive (update its bytes + keep its id), so no second Math Correct file
    # is added to the submission. A file Classroom references is never deleted.
    canonical_result_id, superseded_files = _canonical_for_submission(
        course_id, coursework_id, submission_id, token=token)
    if canonical_result_id and canonical_result_id != result_id:
        # Another result is currently canonical for this submission. That prior
        # correction's report file is the one currently on the submission; bring
        # it current by patching its bytes to this report (same submission,
        # newer valid report). Do NOT create a second Math Correct file.
        log.info("reconciling canonical report for result %s: prior canonical "
                 "result %s owns the submission attachment", result_id,
                 canonical_result_id)
        try:
            reconciled = _reconcile_superseded_report(
                token, course_id, coursework_id, submission_id,
                result_id=result_id, canonical_result_id=canonical_result_id,
                account_email=account_email,
                detail=detail,
                render_fn=(lambda r=result, d=detail:
                           render_report_pdf(r, detail=d)))
            if reconciled.get("drive_file_id"):
                drive_file_id = reconciled["drive_file_id"]
                state["drive_file_id"] = drive_file_id
                state["report_filename"] = (
                    reconciled.get("report_filename") or filename)
                state["previous_drive_file_id"] = (
                    reconciled.get("previous_drive_file_id"))
                state["status"] = STATUS_UPLOADED
                # The reconciled file replaces the prior one. Remove the prior
                # result's file id from ``superseded_ids`` so the attach step
                # does not try to ADD it again (the canonical path already
                # patched the existing file in place).
                superseded_ids.discard(reconciled["drive_file_id"])
                existing_ids.discard(reconciled["drive_file_id"])
        except Exception as exc:  # noqa: BLE001
            log.warning("canonical report reconciliation failed for result %s: %s",
                        result_id, exc)
            # Fall through to the normal upload path rather than failing the
            # whole attachment — creating a fresh file is acceptable here.

    # ---- pre-flight read; also the authoritative student identity ---------
    try:
        current = gc.get_student_submission(token, course_id, coursework_id,
                                            submission_id)
    except gc.ClassroomApiError as exc:
        state["status"] = STATUS_FAILED
        state["error"] = f"Classroom refused the read ({exc.status})."
        _save(state)
        return AttachmentOutcome(STATUS_FAILED, message=state["error"],
                                 result_id=result_id)

    # ---- identity back-fill ------------------------------------------------
    # The StudentSubmission's own ``userId`` IS the Classroom identity of the
    # student who turned the work in, so it WINS over the locally stored
    # student_id. Everything downstream (the Drive share, the filename) keys
    # off this id, which is what makes it structurally impossible to share one
    # student's report with another: a stale or wrong local row cannot
    # redirect the share away from the submission we actually attached to.
    submission_user_id = current.get("userId")
    identity_changed = bool(submission_user_id and submission_user_id != student_id)
    if identity_changed:
        log.info("student identity for result %s taken from the Classroom "
                 "submission (userId), not from the local row", result_id)
        student_id = submission_user_id
        # Drop the stored name too: it belonged to the PREVIOUS id, so keeping
        # it would label this student's report with someone else's name.
        # build_report_filename falls back to a neutral placeholder if the
        # fresh lookup below cannot resolve one.
        result = dict(result, student_id=student_id, student_name=None)
    if student_id:
        state["student_id"] = student_id
    # Re-resolve the display name when the identity changed (the stored name
    # may belong to the previous id) or when it is simply missing.
    if student_id and (identity_changed or not result.get("student_name")):
        try:
            profile = gc.get_user_profile(token, student_id) or {}
            name = (profile.get("name") or {}).get("fullName") \
                or profile.get("fullName")
            if name:
                result = dict(result, student_name=name)
        except Exception as exc:  # noqa: BLE001
            # Naming is cosmetic; the attachment itself does not depend on it.
            log.warning("could not resolve student name for the report: %s", exc)

    filename = build_report_filename(
        result.get("display_name") or result.get("student_name"),
        assignment_title)
    state["report_filename"] = previous_filename or filename

    if not gc.submission_can_be_modified(current):
        state["status"] = STATUS_BLOCKED
        state["error"] = (
            "Google only lets this app modify submissions for assignments the "
            "app itself created. Attach the report from the Classroom UI for "
            "this assignment.")
        _save(state)
        return AttachmentOutcome(
            STATUS_BLOCKED, message=state["error"], result_id=result_id,
            report_filename=filename)

    # ---- already attached? (idempotency / no duplicate reports) ----------
    drive_file_id = state.get("drive_file_id")
    existing_ids = _attachment_ids(current)
    # Canonical-report dedup (§1/§2/§6): if this submission already has a
    # Math Correct report belonging to a DIFFERENT result, that is the
    # superseded file we are about to replace in place. It must never become
    # "already_on_submission" for THIS result, or we would short-circuit and
    # leave the old report in place as if it were current.
    superseded_by_other_result = _our_report_files_on_submission(
        token, existing_ids, exclude_result_id=result_id,
        account_email=account_email)
    superseded_ids = {f["drive_file_id"] for f in superseded_by_other_result}

    # The fingerprint decides whether this is the SAME report already on the
    # submission or a re-mark. It MUST be computed before the "already
    # attached" short-circuit: now that the Drive file is retained, the file
    # id stays attached forever, so a re-mark would otherwise be served as the
    # previous report. A changed hash falls through to update the same file.
    previous_hash = state.get("report_hash")
    report_hash = _report_fingerprint(result, detail=detail)
    state["report_hash"] = report_hash
    unchanged = bool(report_hash) and report_hash == previous_hash

    # A retained report keeps its Drive file id, so a NULL id means our row
    # LOST it (legacy rows from the old clean-after-attach policy read
    # VERIFIED/CLEANED with no id - the exact "no report was uploaded" bug).
    # Never assume the report is gone: try to ADOPT it from the submission's
    # own attachments, matched by OUR appProperties only. If it cannot be
    # found, the code below REPAIRS by publishing a fresh file - it must never
    # report success without proven evidence.
    superseded_id = None
    if not drive_file_id:
        drive_file_id = _recover_attached_report(token, result_id, existing_ids)
        if drive_file_id:
            state["drive_file_id"] = drive_file_id
            _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_ATTACHED)
            log_event("classroom.report", "recovered attached report file",
                      result_id=result_id, drive_file_id=drive_file_id)

    already_on_submission = bool(
        drive_file_id and drive_file_id in existing_ids
        and drive_file_id not in superseded_ids)
    if already_on_submission:
        drive_check = verify_drive_accessible(token, drive_file_id)
        if unchanged and drive_check.get("ok"):
            state["status"] = STATUS_VERIFIED
            state["error"] = None
            state["report_filename"] = state.get("report_filename") or filename
            _save(state)
            # The file is on the submission; keep it so the student can open it.
            _cleanup.record_retained(result_id)
            return AttachmentOutcome(
                STATUS_VERIFIED,
                message="Correction report is already attached to this "
                        "submission (verified).",
                result_id=result_id, drive_file_id=drive_file_id,
                report_filename=state["report_filename"], drive=drive_check)
        # The report is on the submission but its Drive file is no longer
        # reachable: REPAIR by publishing one fresh, working file and attaching
        # that. The old reference is left untouched because Classroom can only
        # ADD attachments, never remove them.
        #
        # A mere re-mark (changed fingerprint) is NOT this case: it keeps the
        # working file, updates it IN PLACE below and re-verifies - which is
        # what prevents "Report (1).pdf", "Report (2).pdf" ...
        if not drive_check.get("ok"):
            log.warning(
                "repairing unreachable report for result %s (reason=%s)",
                result_id, drive_check.get("reason"))
            superseded_id = drive_file_id
            drive_file_id = None
            already_on_submission = False
            state["drive_file_id"] = None

    # ---- render + upload (or update the existing Drive file) -------------
    # A retry re-uses the PDF bytes we already generated (§7) - but ONLY when
    # the fingerprint proves those bytes belong to the correction being
    # attached NOW. A re-mark must never be published as yesterday's report.
    cached = (bytes(state["content_bytes"])
              if state.get("content_bytes") and report_hash == previous_hash
              else None)
    try:
        content = cached if cached else render_report_pdf(result, detail=detail)
    except Exception as exc:  # noqa: BLE001
        state["status"] = STATUS_FAILED
        state["error"] = f"Could not render the report PDF: {exc}"
        _save(state)
        return AttachmentOutcome(STATUS_FAILED, message=state["error"],
                                 result_id=result_id)

    # ---- validate the PDF BEFORE it is uploaded anywhere (§25) -----------
    # An empty, truncated or non-PDF payload must never reach Drive and must
    # never be reported as uploaded. This is the guard that turns a silently
    # broken generator into an honest PDF_VALIDATION_ERROR.
    validation = _validate_pdf(content)
    if not validation.get("ok"):
        state["status"] = STATUS_PDF_INVALID
        state["error"] = (f"{ERROR_PDF}: the generated report is not a valid "
                          f"PDF ({validation.get('reason')}), so it was NOT "
                          f"uploaded or attached.")
        _save(state)
        log_event("classroom.report", "report PDF failed validation",
                  result_id=result_id, reason=validation.get("reason"))
        return AttachmentOutcome(STATUS_PDF_INVALID, message=state["error"],
                                 result_id=result_id,
                                 report_filename=filename)

    try:
        # The file this attempt is superseding, if any - kept for the audit
        # trail so a replaced report can still be accounted for (§9).
        stale_file_id = drive_file_id or superseded_id
        if drive_file_id:
            # Reuse our own file rather than creating "Report (1).pdf" (§14).
            # But ONLY if we still own it: Classroom's modifyAttachments
            # requires ownership, and reusing a file owned by anyone else
            # reproduces the @OwnerAccessRequired 403 forever.
            ownership = gc.verify_drive_ownership(
                token, drive_file_id, account_email=account_email)
            if not ownership["ok"]:
                # Re-create under the CURRENT identity instead of blindly
                # retrying a permanently-failing attach (§3, §16).
                log.warning(
                    "report file %s is not owned by this account (%s); "
                    "re-creating it under the current identity",
                    drive_file_id, ownership["reason"])
                _cleanup.set_lifecycle(
                    result_id, _cleanup.LIFECYCLE_UPLOADED,
                    previous_drive_file_id=drive_file_id,
                    cleanup_error=(
                        f"{ERROR_OWNERSHIP}: recorded Drive file "
                        f"{drive_file_id} is owned by "
                        f"{ownership['owners'] or ['unknown']}, not by "
                        f"{account_email or 'the connected account'}; a fresh "
                        f"file was created under the current account. The old "
                        f"file was left untouched."))
                drive_file_id = None
        if drive_file_id:
            # Same report, corrected version -> update in place. This is what
            # prevents "Report (1).pdf", "Report (2).pdf" …
            gc.replace_drive_file_content(token, drive_file_id, content)
        else:
            temp_token = _cleanup.new_temp_token()
            uploaded = gc.upload_report_to_drive(
                token, filename, content,
                app_properties=_cleanup.stamp_properties(result_id, temp_token))
            drive_file_id = uploaded["id"]
            # record_upload() writes straight to the database, but every later
            # _save() below re-writes drive_file_id from this dict - so the in
            # memory copy MUST be kept in step, or the file id is wiped and a
            # retry uploads a second copy (§7, §14).
            state["drive_file_id"] = drive_file_id
            owners = gc.drive_file_owners(uploaded) or []
            _cleanup.record_upload(
                result_id, drive_file_id=drive_file_id,
                owner_email=owners[0] if owners else account_email,
                temp_token=temp_token,
                previous_drive_file_id=stale_file_id,
                content_bytes=content)
    except Exception as exc:  # noqa: BLE001
        state["status"] = STATUS_UPLOAD_FAILED
        state["error"] = f"Google Drive upload failed: {exc}"
        _save(state)
        return AttachmentOutcome(STATUS_UPLOAD_FAILED, message=state["error"],
                                 result_id=result_id,
                                 report_filename=filename)

    # ---- verify the Drive upload BEFORE trusting it (§28) ----------------
    # A returned file id is not proof: the file may be missing, trashed, the
    # wrong mime type, zero bytes or someone else's. Re-read Drive and compare
    # the downloaded bytes with what we generated; only then is the upload real
    # enough to attach and to persist as the job's drive_file_id.
    drive_meta = _verify_drive_upload(token, drive_file_id, content)
    if not drive_meta.get("ok"):
        state["status"] = STATUS_DRIVE_VERIFY_FAILED
        state["error"] = (f"{ERROR_DRIVE_VERIFY}: the report did not appear as "
                          f"a readable PDF in Google Drive "
                          f"({drive_meta.get('reason')}), so it was NOT "
                          f"attached.")
        _save(state)
        log_event("classroom.report", "drive upload verification failed",
                  result_id=result_id, drive_file_id=drive_file_id,
                  reason=drive_meta.get("reason"))
        return AttachmentOutcome(STATUS_DRIVE_VERIFY_FAILED,
                                 message=state["error"], result_id=result_id,
                                 drive_file_id=drive_file_id,
                                 report_filename=filename)
    state["drive_file_id"] = drive_file_id

    # ---- verify ownership BEFORE attaching (§3) ---------------------------
    ownership = gc.verify_drive_ownership(
        token, drive_file_id, account_email=account_email)
    if not ownership["ok"]:
        detail = (ownership.get("detail")
                  or f"owner(s)={ownership.get('owners') or ['unknown']}, "
                     f"attached-by={account_email or 'unknown'}")
        state["status"] = STATUS_OWNERSHIP_ERROR
        state["error"] = (f"{ERROR_OWNERSHIP}: this app must OWN the Drive "
                          f"file to attach it to a Classroom submission "
                          f"({detail}). The file was not attached and was not "
                          f"deleted, so it can still be retried.")
        _save(state)
        _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_UPLOADED,
                               cleanup_error=state["error"])
        log_event("classroom.report", "report ownership check failed",
                  result_id=result_id, drive_file_id=drive_file_id,
                  classroom_account=account_email,
                  drive_owners=",".join(ownership.get("owners") or []) or "unknown",
                  reason=ownership.get("reason"))
        return AttachmentOutcome(STATUS_OWNERSHIP_ERROR, message=state["error"],
                                 result_id=result_id, drive_file_id=drive_file_id,
                                 report_filename=filename,
                                 ownership=ownership)
    state["status"] = STATUS_UPLOADED
    state["error"] = None
    # The bytes are the retry buffer: kept until the temporary Drive file is
    # cleaned up, then dropped (§7, §10).
    state["content_bytes"] = content
    # Canonical report bookkeeping (§1/§2/§6): this result is now the
    # canonical correction report for the submission, so a future re-correction
    # replaces this file in place instead of adding a second Math Correct file
    # to the submission.
    _mark_canonical(course_id, coursework_id, submission_id, result_id,
                    drive_file_id=drive_file_id)
    _save(state)

    # ---- share with THIS student only (never public) ---------------------
    if share_with_student and student_id:
        try:
            profile = gc.get_user_profile(token, student_id)
            email = profile.get("emailAddress")
            if email:
                gc.share_drive_file(token, drive_file_id, email)
        except Exception as exc:  # noqa: BLE001
            # Best-effort: Classroom also grants access to attachments when
            # the submission is returned, so this must not fail the attach.
            log.warning("could not share report with student: %s", exc)

    # ---- attach to THIS student's submission ------------------------------
    # NOTE: the Classroom ModifyAttachmentsRequest only supports ADDING. There
    # is no removeAttachments field (a live call proved Google rejects it with
    # 400 "Unknown name removeAttachments"). Duplicate suppression therefore
    # happens BEFORE this call - the early "already attached" check above and
    # the reuse of one Drive file per result - never by deleting afterwards.
    #
    # Canonical-report dedup (§1/§2/§6): if the submission already carries a
    # Math Correct report for a DIFFERENT result, we never ADD a second Math
    # Correct file. Instead we reuse the canonical file id (patched in place
    # above) so the submission ends up pointing at exactly one Math Correct
    # report - the current one. ``foreign`` still counts any OTHER attachments
    # (student files, mark schemes) so the UI can show them.
    foreign = [fid for fid in existing_ids
               if fid not in superseded_ids and fid != drive_file_id]
    try:
        if not already_on_submission and drive_file_id not in existing_ids:
            gc.modify_submission_attachments(
                token, course_id, coursework_id, submission_id,
                add_drive_file_ids=[drive_file_id])
    except gc.ClassroomApiError as exc:
        # The file is deliberately KEPT so "Retry attachment" can reuse it
        # without re-marking the student or regenerating the PDF (§7, §15).
        state["status"] = STATUS_ATTACH_FAILED
        state["error"] = (
            f"{ERROR_ATTACH}: Classroom refused the attachment ({exc.status}). "
            + (exc.detail or "")[:200])
        _save(state)
        _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_UPLOADED,
                               cleanup_error=state["error"])
        return AttachmentOutcome(STATUS_ATTACH_FAILED, message=state["error"],
                                 result_id=result_id, drive_file_id=drive_file_id,
                                 report_filename=filename)

    state["status"] = STATUS_ATTACHED
    _save(state)
    _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_ATTACHED)

    # ---- verify by reading the submission back ---------------------------
    try:
        check = verify_attached(token, course_id, coursework_id,
                                submission_id, drive_file_id)
    except Exception as exc:  # noqa: BLE001
        state["status"] = STATUS_VERIFY_FAILED
        state["error"] = f"{ERROR_VERIFY}: could not verify the attachment: {exc}"
        _save(state)
        _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_ATTACHED,
                               cleanup_error=state["error"])
        return AttachmentOutcome(STATUS_VERIFY_FAILED, message=state["error"],
                                 result_id=result_id, drive_file_id=drive_file_id)

    if not check["verified"]:
        state["status"] = STATUS_VERIFY_FAILED
        state["error"] = (f"{ERROR_VERIFY}: Classroom accepted the request but "
                          f"the report is not present on the student "
                          f"submission. The file has been kept for a retry.")
        _save(state)
        _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_ATTACHED,
                               cleanup_error=state["error"])
        return AttachmentOutcome(STATUS_VERIFY_FAILED, message=state["error"],
                                 result_id=result_id, drive_file_id=drive_file_id)

    # ---- Post-attach: the Drive file MUST still be reachable ----------------
    # Classroom holds a REFERENCE to this Drive file. If it is missing or
    # trashed the student sees "couldn't be opened / may have been deleted",
    # so we re-read it and only then treat the attachment as a success.
    drive_check = verify_drive_accessible(token, drive_file_id)
    if not drive_check.get("ok"):
        state["status"] = STATUS_VERIFY_FAILED
        state["error"] = (
            f"DRIVE_ACCESS_ERROR: the report is on the submission but its "
            f"Drive file is not reachable ({drive_check.get('reason')}). "
            f"The file was kept for a retry.")
        _save(state)
        _cleanup.set_lifecycle(result_id, _cleanup.LIFECYCLE_ATTACHED,
                               cleanup_error=state["error"])
        log_event("classroom.report", "attached report drive file unreachable",
                  result_id=result_id, drive_file_id=drive_file_id,
                  reason=drive_check.get("reason"))
        return AttachmentOutcome(STATUS_VERIFY_FAILED, message=state["error"],
                                 result_id=result_id, drive_file_id=drive_file_id,
                                 report_filename=filename, drive=drive_check)

    # ---- CONFIRMED: attached, reachable and verified ----------------------
    # The file is RETAINED because Classroom references it - it is NEVER
    # deleted here. Deleting it is what produced "the document couldn't be
    # opened. It may have been deleted."
    state["status"] = STATUS_VERIFIED
    state["error"] = None
    _save(state)
    _cleanup.record_retained(result_id)
    log_event("classroom.report", "report attached and retained",
              result_id=result_id, drive_file_id=drive_file_id)

    return AttachmentOutcome(
        STATUS_VERIFIED,
        message="Correction report attached to the student's submission "
                "and verified; the Drive file is kept so the student can "
                "open it.",
        result_id=result_id, drive_file_id=drive_file_id,
        report_filename=filename,
        drive=drive_check,
        other_attachments=len(foreign))