# Statuses stored in report_attachments.status. These are DELIBERATELY distinct
# so a Drive housekeeping problem never reads as "the correction failed" (§20).
STATUS_PENDING = "PENDING"
STATUS_UPLOADED = "UPLOADED"
STATUS_ATTACHED = "ATTACHED"
STATUS_VERIFIED = "VERIFIED"
STATUS_UPLOAD_FAILED = "DRIVE_UPLOAD_FAILED"
STATUS_OWNERSHIP_ERROR = "REPORT_ATTACHMENT_OWNERSHIP_ERROR"
STATUS_ATTACH_FAILED = "CLASSROOM_ATTACHMENT_FAILED"
STATUS_VERIFY_FAILED = "ATTACHMENT_VERIFY_FAILED"
#: The generated bytes are not a real, openable PDF - nothing was uploaded.
STATUS_PDF_INVALID = "PDF_VALIDATION_ERROR"
#: The Drive upload returned but the file could not be proven to exist as a
#: readable PDF of the right size, so it was never attached.
STATUS_DRIVE_VERIFY_FAILED = "DRIVE_VERIFY_FAILED"
STATUS_CLEANUP_PENDING = "CLEANUP_PENDING"
STATUS_FAILED = "FAILED"          # legacy value, still read for old rows
STATUS_BLOCKED = "BLOCKED_NOT_MODIFIABLE"
STATUS_SKIPPED = "SKIPPED"

#: Every status that means "the report is NOT on the submission", i.e. the
#: teacher can retry. Deliberately a tuple so no caller can quietly test for a
#: single legacy value and stop seeing the newer, more specific ones (§20).
FAILED_STATUSES = (
    STATUS_FAILED,          # legacy rows
    STATUS_UPLOAD_FAILED,
    STATUS_ATTACH_FAILED,
    STATUS_VERIFY_FAILED,
    STATUS_OWNERSHIP_ERROR,
    STATUS_PDF_INVALID,
    STATUS_DRIVE_VERIFY_FAILED,
)

#: A confirmed attachment. The report IS on the submission in all of these;
#: ``CLEANUP_PENDING`` only means the Drive housekeeping is outstanding (§12).
ATTACHED_STATUSES = (STATUS_VERIFIED, STATUS_CLEANUP_PENDING, STATUS_ATTACHED)

#: Stable machine-readable error codes surfaced in the API and the logs (§3/§20).
ERROR_OWNERSHIP = "REPORT_ATTACHMENT_OWNERSHIP_ERROR"
ERROR_UPLOAD = "REPORT_DRIVE_UPLOAD_FAILED"
ERROR_ATTACH = "REPORT_ATTACHMENT_FAILED"
ERROR_VERIFY = "REPORT_ATTACHMENT_VERIFY_FAILED"
ERROR_PDF = "PDF_VALIDATION_ERROR"
ERROR_DRIVE_VERIFY = "DRIVE_VERIFY_ERROR"
ERROR_CLEANUP = "REPORT_CLEANUP_PENDING"

# Characters that are illegal in filenames on at least one target platform.
_ILLEGAL = r'[\x00-\x1f<>:"/\\|?*]'
_ILLEGAL_RE = re.compile(_ILLEGAL)
_WS_RE = re.compile(r"\s+")
_MAX_STEM = 120


def sanitize_component(value: str | None, *, fallback: str = "report") -> str:
    """Make one safe path/filename component.

    Removes control characters and the Windows/posix-illegal set
    ``/ \\ : * ? " < > |``, collapses whitespace, drops path separators and
    '..' traversal, and caps the length. Never returns an empty string or a
    dot-only name, so it can never produce a filesystem escape.
    """
    text = unicodedata.normalize("NFC", str(value or "")).strip()
    text = _ILLEGAL_RE.sub(" ", text)
    text = _WS_RE.sub(" ", text).strip()
    # A leading '-' would be read as a CLI flag; '.' / '..' would traverse.
    text = text.replace("..", " ").lstrip(".- ").strip()
    if len(text) > _MAX_STEM:
        text = text[:_MAX_STEM].rstrip(" .-")
    return text or fallback


def build_report_filename(student_name: str | None, assignment_title: str | None,
                          *, extension: str = ".pdf") -> str:
    """``StudentName_Assignment_Correction_Report.pdf`` - predictable and safe.

    Deterministic on purpose: Drive auto-renames duplicates in a folder, so a
    stable name keeps re-runs from producing "Report (1).pdf" clones.
    """
    student = sanitize_component(student_name, fallback="Student")
    assignment = sanitize_component(assignment_title, fallback="Assignment")
    return f"{student}_{assignment}_Correction_Report{extension}"


def _report_fingerprint(result: dict, *, detail: str) -> str:
    """A stable id for *this exact report*, independent of any filename.

    Two corrections of the same student produce the same ``result_id`` (one
    result row per Classroom submission), so the row id alone cannot tell a
    repeated attach from a re-mark (§14). This hash of everything the PDF
    actually depends on - marks, per-question detail, the student it is for and
    the render detail - can. A repeated attach of an unchanged correction
    therefore matches, while a re-mark does not, which is exactly the
    distinction "no duplicate reports" needs.
    """
    payload = {
        "coursework": result.get("coursework_id"),
        "submission": result.get("submission_id"),
        "student": result.get("student_id"),
        "name": result.get("display_name") or result.get("student_name"),
        "earned": result.get("earned"),
        "available": result.get("available"),
        "percentage": result.get("percentage"),
        "grade": result.get("provisional_grade"),
        "detail": detail,
        "marks": result.get("result_json"),
    }
    blob = json.dumps(payload, sort_keys=True, default=str,
                      ensure_ascii=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


