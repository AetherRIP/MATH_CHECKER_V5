def _row_for(result_id: str) -> dict | None:
    row = query_one(
        "SELECT * FROM report_attachments WHERE result_id = ?", (result_id,))
    return dict(row) if row else None


def get_state(result_id: str) -> dict:
    """Attachment state for one result (for the teacher UI).

    Reports the correction outcome and the Drive file lifecycle SEPARATELY, so
    a pending cleanup can never read as a failed correction (§12).
    """
    row = _row_for(result_id)
    if row is None:
        row = {"result_id": result_id, "status": STATUS_PENDING,
               "attempts": 0, "error": None, "drive_file_id": None,
               "report_filename": None, "lifecycle": _cleanup.LIFECYCLE_NONE}
    out = dict(row)
    # The PDF bytes are transport, never something the UI should receive.
    out.pop("content_bytes", None)
    # A confirmed attachment stays ATTACHED even when the Drive cleanup is
    # still pending: the report is on the submission either way (§12). But it
    # ALSO needs a real Drive file id - a legacy VERIFIED/CLEANED row whose id
    # is NULL (the report was deleted) is NOT attached, and must never read as
    # one, or the UI shows a tick for a report the student cannot open.
    out["attached"] = (row.get("status") in ATTACHED_STATUSES
                       and bool(row.get("drive_file_id")))
    # The grade is its OWN state with its own evidence (§19). Assuming
    # "attached implies returned" is exactly the kind of false tick this
    # whole change exists to remove, so it is never inferred.
    from . import managed as _managed
    grade = _managed.grade_return_state(out.get("coursework_id"),
                                        out.get("submission_id"))
    out["grade_returned"] = grade["returned"]
    out["grade_return_note"] = grade.get("reason")
    lifecycle = row.get("lifecycle") or _cleanup.LIFECYCLE_NONE
    out["drive_cleanup"] = (
        "cleaned" if lifecycle == _cleanup.LIFECYCLE_CLEANED
        else "retained" if lifecycle in _cleanup.RETAINED_LIFECYCLES
        else "pending" if lifecycle in _cleanup.PENDING_CLEANUP
        else "not_needed" if lifecycle == _cleanup.LIFECYCLE_NONE
        else lifecycle.lower())
    out["retryable"] = row.get("status") in FAILED_STATUSES + (STATUS_PENDING,)
    out["fallback"] = fallback_actions(result_id) if (
        row.get("status") in FAILED_STATUSES
        or row.get("status") in (STATUS_BLOCKED, STATUS_SKIPPED, STATUS_PENDING)
    ) else None
    return out


def fallback_actions(result_id: str) -> dict | None:
    """The manual route for teachers when the API cannot attach the file.

    Google only lets this app modify submissions for coursework the app
    created, so for teacher-created assignments the honest fallback is:
    download the PDF and attach it on the student's submission in Classroom.

    Deliberately returns only a link we KNOW is valid (the assignment's own
    stored ``alternate_link``). Google exposes no stable deep link to one
    student's submission, so we do not invent one - the teacher is told which
    student to open instead.
    """
    from .. import db
    row = db.query_one(
        """
        SELECT r.id, r.coursework_id, r.submission_id, r.student_id,
               r.student_name,
               cw.alternate_link, cw.title AS assignment
          FROM results r
          LEFT JOIN coursework cw ON cw.id = r.coursework_id
         WHERE r.id = ?
        """, (result_id,))
    if row is None:
        return None
    if not row["submission_id"]:
        return None        # nothing in Classroom to attach to
    # Canonical name: nickname -> Classroom name, resolved by student id (or
    # recovered from the submission id for older rows). A sparse result row can
    # have no stored name at all — never interpolate None into teacher prose.
    from .. import student_identity
    _who = student_identity.resolve(row["student_id"],
                                    submission_id=row["submission_id"],
                                    snapshot_name=row["student_name"])
    filename = build_report_filename(_who["display_name"], row["assignment"])
    # Prose needs to know whether we actually know who this is: with no
    # Classroom identity at all it must read "the student's submission", never
    # a bare "Student's submission" and never "None's".
    who = _who["nickname"] or _who["classroom_name"] or "the student"
    return {
        "pdf_url": f"/api/results/{result_id}/export?format=pdf&detail=standard",
        "filename": filename,
        "classroom_url": row["alternate_link"],
        "student_name": row["student_name"],
        "display_name": _who["display_name"],
        "submission_id": row["submission_id"],
        "instructions": (
            f"Download the report, open the assignment in Google Classroom, "
            f"open {who}'s submission, and attach the file. "
            f"Google only lets this app attach automatically to assignments "
            f"the app itself created."),
    }


def list_states(coursework_id: str | None = None, *,
                statuses: tuple[str, ...] | None = None) -> list[dict]:
    sql = "SELECT * FROM report_attachments"
    params: list = []
    if coursework_id:
        sql += " WHERE coursework_id = ?"
        params.append(coursework_id)
    sql += " ORDER BY updated_at DESC"
    rows = [dict(r) for r in query(sql, params)]
    if statuses:
        rows = [r for r in rows if r["status"] in statuses]
    return rows


