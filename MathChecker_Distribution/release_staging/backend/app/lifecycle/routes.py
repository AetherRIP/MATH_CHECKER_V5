"""Lifecycle API: heartbeat, goodbye and the real state of the server.

``GET`` rather than ``POST`` on purpose. A heartbeat is tiny, idempotent and
fires every 30 seconds per open tab; ``POST`` would drag in the CSRF token and
turn the most frequent request in the app into a mutating one. A ``GET`` also
survives ``fetch(..., {keepalive: true})`` on ``pagehide``, which is how a
closed tab says goodbye without the server waiting for the timeout. Nothing
here reads or writes a secret, a student record or any personal data — the
payload is a session id chosen by the browser and the counters derived from it.
"""

from __future__ import annotations

from fastapi import APIRouter, Query

from .monitor import get_monitor
from .sessions import MAX_SESSION_ID

router = APIRouter(prefix="/api/lifecycle", tags=["lifecycle"])

SESSION_ID = Query(..., min_length=1, max_length=MAX_SESSION_ID,
                   description="Browser-session id generated by the tab")


@router.get("/heartbeat")
def heartbeat(sid: str = SESSION_ID, hidden: bool = False) -> dict:
    """Say "this tab is still here" and get the current lifecycle state back.

    ``hidden`` records whether the tab is in the background. A hidden tab is
    still an active session (the teacher may come straight back to it); the
    flag exists so the state can be reported honestly rather than guessed.
    """
    monitor = get_monitor()
    result = monitor.beat(sid, hidden=hidden)
    return {"ok": bool(result.get("accepted")), **result}


@router.get("/leave")
def leave(sid: str = SESSION_ID) -> dict:
    """Say goodbye: this tab is closing, so stop counting it as active."""
    monitor = get_monitor()
    return {"ok": True, **monitor.leave(sid)}


@router.get("/status")
def status() -> dict:
    """The real lifecycle state. Read-only: it never registers a session.

    Deliberately side-effect free so the launcher, ``--stop`` and the supervisor
    can ask "is the backend up?" without keeping it awake — a status poll must
    never be mistaken for a user.
    """
    return get_monitor().snapshot()


def register(app) -> None:
    """Attach the lifecycle API (same convention as the other route modules)."""
    app.include_router(router)
